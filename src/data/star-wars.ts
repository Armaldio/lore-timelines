import type { DatePlacement, Occurrence, Universe } from '../domain'

const bby = (n: number): DatePlacement => ({ kind: 'exact', label: `${n} BBY`, value: `-${String(n).padStart(4, '0')}` })
const aby = (n: number): DatePlacement => ({ kind: 'exact', label: `${n} ABY`, value: String(n).padStart(4, '0') })
