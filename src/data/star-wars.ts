const occ = (id: string, worldId: string, placement: DatePlacement, spoiler: Occurrence['spoiler'], sourceIds: string[], uncertainty?: string): Occurrence =>
  ({ id: `${id}-occ`, eventId: id, worldId, placement, spoiler, sourceIds, ...(uncertainty ? { uncertainty } : {}) })

