const edge = (from: string, to: string, kind: 'leads-to' | 'related' = 'leads-to') =>
  ({ id: `sw-edge-${from}-${to}`, fromOccurrenceId: `${from}-occ`, toOccurrenceId: `${to}-occ`, kind })

